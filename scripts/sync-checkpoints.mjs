#!/usr/bin/env node
/**
 * Syncs the skills with the IsAgentReady checkpoint catalog.
 *
 * Usage:
 *   node scripts/sync-checkpoints.mjs [--snapshot <file>] [--source <url>] [--check] [--root <dir>] [--skills a,b]
 *
 * Without --check, the script writes the checkpoint table in each SKILL.md and
 * the generated references/checkpoints.md file of each skill.
 * With --check, the script writes nothing. It exits with code 1 when a file is
 * out of date, when a SKILL.md lists a retired checkpoint, or when a SKILL.md
 * misses an active checkpoint of its category.
 *
 * Exit codes: 0 = pass, 1 = check or validation failure, 2 = source or usage error.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const DEFAULT_SOURCE = "https://isagentready.com/api/v2/checkpoints?include_retired=true";
export const METHODOLOGY_URL = "https://isagentready.com/en/methodology";
export const TABLE_START = "<!-- checkpoints:start (generated by scripts/sync-checkpoints.mjs) -->";
export const TABLE_END = "<!-- checkpoints:end -->";

export const SKILL_BY_CATEGORY = Object.freeze({
  discovery: "ai-content-discovery",
  structured_data: "structured-data",
  semantics: "content-semantics",
  agent_protocols: "agent-protocols",
  security: "security-trust",
  training_exposure: "ai-content-discovery",
});

const INFORMATIONAL_CATEGORY = "training_exposure";
const SKILLS = [...new Set(Object.values(SKILL_BY_CATEGORY))];
const STAGES = ["find", "read", "act"];
const STRENGTHS = ["MUST", "SHOULD", "MAY", null];
const EVIDENCE_TYPES = ["measured_study", "scanner_data", "recommendation"];
const AR_MAPPINGS = ["full", "partial", "none"];
const PLACEHOLDERS = ["domain", "origin"];
const READ_ONLY_TOOLS = ["curl", "jq", "grep", "head", "tail", "tr", "wc", "sort", "uniq", "cut", "sed"];
const READ_METHODS = ["GET", "HEAD"];
const BODY_FLAGS = /^--(data(-[a-z]+)?|json|form(-string)?|upload-file)(=|$)/;
const BODY_SHORT_FLAGS = ["d", "F", "T"];
const ARGUMENT_SHORT_FLAGS = "oOwAHeuxKbcmrEzYyCQ";
const EXIT = Object.freeze({ pass: 0, fail: 1, error: 2 });

const STABLE_ID = /^ia\.[a-z0-9]+(-[a-z0-9]+)*$/;
const LEGACY_ID = /^(\d+\.\d+|te\.\d+)$/;
const AR_ID = /^AR-(FIND|READ|ACT)-\d{2}$/;

const isRetired = (definition) => Boolean(definition.lifecycle?.retired);
const escapeRegExp = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const capitalize = (value) => value.charAt(0).toUpperCase() + value.slice(1);

const legacyKey = (legacyId) =>
  legacyId.startsWith("te.") ? [99, Number(legacyId.slice(3))] : legacyId.split(".").map(Number);

const byLegacyId = (a, b) => {
  const [a1, a2] = legacyKey(a.legacy_id);
  const [b1, b2] = legacyKey(b.legacy_id);
  return a1 - b1 || a2 - b2;
};

/** Returns the active, scored checkpoints that a skill must list in its SKILL.md. */
export const activeForSkill = (skill, definitions) =>
  definitions
    .filter((definition) => !isRetired(definition))
    .filter((definition) => definition.category !== INFORMATIONAL_CATEGORY)
    .filter((definition) => SKILL_BY_CATEGORY[definition.category] === skill)
    .sort(byLegacyId);

const informationalForSkill = (skill, definitions) =>
  definitions
    .filter((definition) => !isRetired(definition))
    .filter((definition) => definition.category === INFORMATIONAL_CATEGORY)
    .filter((definition) => SKILL_BY_CATEGORY[definition.category] === skill)
    .sort(byLegacyId);

/** Accepts an array, `{ checkpoints: [] }` or `{ data: [] }` and returns the definitions and the version. */
export const normalizePayload = (payload) => {
  const definitions = Array.isArray(payload) ? payload : (payload?.checkpoints ?? payload?.data);
  if (!Array.isArray(definitions) || definitions.length === 0) {
    throw new Error("The payload has no checkpoint definitions.");
  }
  const topLevel = Array.isArray(payload) ? undefined : (payload.methodology_version ?? payload.version);
  const version = topLevel ?? definitions.find((definition) => definition.methodology_version)?.methodology_version;
  if (typeof version !== "string" || version.length === 0) {
    throw new Error("The payload has no methodology version.");
  }
  return { version, definitions };
};

const stripQuotes = (command) => command.replace(/'[^']*'|"(?:[^"\\]|\\.)*"/g, "Q");

const curlMethodIsRead = (tokens) => {
  for (let index = 0; index < tokens.length; index += 1) {
    const token = tokens[index];
    if (BODY_FLAGS.test(token)) return false;
    if (token === "--request" || token.startsWith("--request=")) {
      const method = token.includes("=") ? token.split("=")[1] : tokens[index + 1];
      if (!READ_METHODS.includes(method)) return false;
      continue;
    }
    if (!/^-[A-Za-z]/.test(token)) continue;
    for (let position = 1; position < token.length; position += 1) {
      const flag = token[position];
      if (BODY_SHORT_FLAGS.includes(flag)) return false;
      if (flag === "X") {
        const method = token.slice(position + 1) || tokens[index + 1];
        if (!READ_METHODS.includes(method)) return false;
        break;
      }
      if (ARGUMENT_SHORT_FLAGS.includes(flag)) break;
    }
  }
  return true;
};

/** Returns true when a curl invocation only reads (GET or HEAD, no request body). */
export const isReadOnlyCurl = (command) => {
  const tokens = stripQuotes(command).split(/\s+/).filter(Boolean);
  const start = tokens.indexOf("curl");
  return start === -1 ? true : curlMethodIsRead(tokens.slice(start + 1).filter((token) => !/^[|;&]/.test(token)));
};

const hasFileRedirect = (stripped) =>
  [...stripped.matchAll(/\d?>>?\s*(&\d|\S+)?/g)].some(([, target]) => target !== "/dev/null" && target !== "&1");

/**
 * Returns true when a verify command is read-only: it uses only curl, jq and
 * text filters, curl sends no request body and no write method, and no output
 * goes to a file.
 */
export const isReadOnlyCommand = (command) => {
  const stripped = stripQuotes(command);
  if (hasFileRedirect(stripped)) return false;
  const segments = stripped.split(/\|\||&&|[|;]/).map((segment) => segment.trim()).filter(Boolean);
  return segments.every((segment) => {
    const tokens = segment.split(/\s+/).filter((token) => token !== "!");
    const [tool, ...rest] = tokens;
    if (!READ_ONLY_TOOLS.includes(tool)) return false;
    if (tool === "curl") return curlMethodIsRead(rest);
    if (tool === "sed") return !rest.some((token) => /^(-i|--in-place)/.test(token) || /^-[a-zA-Z]*i/.test(token));
    return true;
  });
};

const definitionErrors = (definition) => {
  const label = `${definition.legacy_id ?? "?"} (${definition.id ?? "?"})`;
  const errors = [];
  const add = (message) => errors.push(`${label}: ${message}`);

  if (!STABLE_ID.test(definition.id ?? "")) add("id must match ia.<slug>");
  if (!LEGACY_ID.test(definition.legacy_id ?? "")) add("legacy_id must look like 4.3 or te.1");
  if (typeof definition.name !== "string" || definition.name.length === 0) add("name is missing");
  if (!(definition.category in SKILL_BY_CATEGORY)) add(`unknown category ${definition.category}`);
  if (!STAGES.includes(definition.stage)) add(`stage must be one of ${STAGES.join(", ")}`);
  if (!STRENGTHS.includes(definition.strength)) add("strength must be MUST, SHOULD, MAY or null");
  if (!EVIDENCE_TYPES.includes(definition.evidence_type)) add(`evidence_type must be one of ${EVIDENCE_TYPES.join(", ")}`);
  if (!AR_MAPPINGS.includes(definition.ar_mapping)) add(`ar_mapping must be one of ${AR_MAPPINGS.join(", ")}`);

  const arIds = definition.ar_practice_ids;
  if (!Array.isArray(arIds) || !arIds.every((arId) => AR_ID.test(arId))) add("ar_practice_ids must be AR-<STAGE>-<NN> values");
  if (definition.ar_mapping === "none" && Array.isArray(arIds) && arIds.length > 0) add("ar_mapping none needs empty ar_practice_ids");

  if (typeof definition.fix?.summary !== "string") add("fix.summary is missing");
  if (!isRetired(definition)) {
    const expectedSkill = SKILL_BY_CATEGORY[definition.category];
    if (definition.fix?.skill?.name !== expectedSkill) add(`fix.skill.name must be ${expectedSkill}`);
    if (definition.fix?.skill?.anchor !== definition.id) add("fix.skill.anchor must equal the stable id");
    if (definition.category !== INFORMATIONAL_CATEGORY && definition.strength === null) add("an active scored checkpoint needs a strength");
  }

  const command = definition.verify?.command;
  if (command !== null && command !== undefined) {
    if (!isReadOnlyCommand(command)) add("verify.command must be read-only (curl and jq, no POST or data flags)");
    const unknown = [...command.matchAll(/(?<!%)\{([a-z_]+)\}/g)].map(([, name]) => name).filter((name) => !PLACEHOLDERS.includes(name));
    if (unknown.length > 0) add(`verify.command has unknown placeholders: ${unknown.join(", ")}`);
  }
  if (typeof definition.verify?.rescan !== "string") add("verify.rescan is missing");
  return errors;
};

const duplicateErrors = (definitions, field) => {
  const seen = new Set();
  return definitions.flatMap((definition) => {
    const value = definition[field];
    if (seen.has(value)) return [`duplicate ${field} ${value}`];
    seen.add(value);
    return [];
  });
};

/** Validates the catalog definitions against the contract fields this repository uses. */
export const validateDefinitions = (definitions) => [
  ...definitions.flatMap(definitionErrors),
  ...duplicateErrors(definitions, "id"),
  ...duplicateErrors(definitions, "legacy_id"),
];

const arCell = (definition) => (definition.ar_practice_ids.length > 0 ? definition.ar_practice_ids.join(", ") : "none");
const strengthCell = (definition) => definition.strength ?? "info";

/** Renders the checkpoint table that sits between the markers in each SKILL.md. */
export const renderTable = (definitions) =>
  [
    "| Legacy | Stable ID | Name | AR IDs | Strength |",
    "|---|---|---|---|---|",
    ...[...definitions]
      .sort(byLegacyId)
      .map((definition) => `| ${definition.legacy_id} | [\`${definition.id}\`](#${definition.id}) | ${definition.name} | ${arCell(definition)} | ${strengthCell(definition)} |`),
  ].join("\n");

const scoringUrl = (version) => `https://isagentready.com/api/v2/methodology/${version}/scoring`;

const renderSteps = (steps) =>
  [...steps]
    .sort((a, b) => (a.order ?? 0) - (b.order ?? 0))
    .flatMap((step, index) => {
      const lines = [`${index + 1}. ${step.action}`];
      if (step.code_example) {
        lines.push("", `   \`\`\`${step.language ?? ""}`, ...step.code_example.split("\n").map((line) => `   ${line}`), "   ```");
      }
      return lines;
    });

const renderDetail = (definition, { linkSkill }) => {
  const lines = [
    `<a id="${definition.id}"></a>`,
    "",
    `### ${definition.legacy_id} ${definition.name}`,
    "",
    `- Stable ID: \`${definition.id}\``,
    `- Stage: ${capitalize(definition.stage)}`,
    `- Strength: ${definition.strength ?? "informational (no strength)"}`,
    `- AR practices: ${arCell(definition)} (mapping: ${definition.ar_mapping})`,
    `- Evidence type: \`${definition.evidence_type}\``,
    `- Fix: ${definition.fix.summary}`,
  ];
  if (linkSkill) lines.push(`- Fix workflow: [SKILL.md](../SKILL.md#${definition.id})`);
  if (definition.verify.expect) lines.push(`- Expected result: ${definition.verify.expect}`);
  lines.push(`- Rescan: \`${definition.verify.rescan}\``);
  if (definition.detail_url) lines.push(`- Details: ${definition.detail_url}`);

  const steps = definition.fix.steps ?? [];
  if (steps.length > 0) lines.push("", "Steps:", "", ...renderSteps(steps));
  lines.push("", "Verify:", "");
  lines.push(...(definition.verify.command ? ["```bash", definition.verify.command, "```"] : ["No read-only shell check exists. Use the rescan command."]));
  return [...lines, ""];
};

const renderSummaryTable = (definitions) => [
  "| Legacy | Stable ID | Name | Stage | Strength | AR IDs | Evidence |",
  "|---|---|---|---|---|---|---|",
  ...definitions.map(
    (definition) =>
      `| ${definition.legacy_id} | [\`${definition.id}\`](#${definition.id}) | ${definition.name} | ${capitalize(definition.stage)} | ${strengthCell(definition)} | ${arCell(definition)} | ${definition.evidence_type} |`,
  ),
];

/** Renders the generated references/checkpoints.md file of one skill. */
export const renderReference = (skill, definitions, version) => {
  const active = activeForSkill(skill, definitions);
  const informational = informationalForSkill(skill, definitions);
  const lines = [
    "<!-- Generated by scripts/sync-checkpoints.mjs. Do not edit by hand. -->",
    "",
    "# Checkpoint reference",
    "",
    "This file is generated by `scripts/sync-checkpoints.mjs`. Do not edit it by hand. Run `node scripts/sync-checkpoints.mjs` to update it.",
    "",
    `- Skill: \`${skill}\``,
    `- Methodology version: \`${version}\``,
    `- Methodology: ${METHODOLOGY_URL}`,
    `- Scoring: ${scoringUrl(version)}`,
    "- Replace `{domain}` with the domain of the site. Each verify command is read-only.",
    "- Strength and evidence type are spec values. They do not change the score.",
    "",
    "## Checkpoints",
    "",
    ...renderSummaryTable(active),
    "",
    "## Details",
    "",
    ...active.flatMap((definition) => renderDetail(definition, { linkSkill: true })),
  ];
  if (informational.length > 0) {
    lines.push(
      "## Informational checks",
      "",
      "These training exposure checks do not change the score. They show how the site is exposed to AI training and bot verification.",
      "",
      ...renderSummaryTable(informational),
      "",
      ...informational.flatMap((definition) => renderDetail(definition, { linkSkill: false })),
    );
  }
  return `${lines.join("\n").trimEnd()}\n`;
};

const tableBlock = (markdown) => {
  const start = markdown.indexOf(TABLE_START);
  const end = markdown.indexOf(TABLE_END);
  if (start === -1 || end === -1 || end < start) return null;
  return markdown.slice(start + TABLE_START.length, end).trim();
};

/** Replaces the checkpoint table between the markers. Returns null when the markers are missing. */
export const updateSkillTable = (markdown, table) => {
  const start = markdown.indexOf(TABLE_START);
  const end = markdown.indexOf(TABLE_END);
  if (start === -1 || end === -1 || end < start) return null;
  return `${markdown.slice(0, start + TABLE_START.length)}\n${table}\n${markdown.slice(end)}`;
};

const tableRows = (markdown) =>
  markdown
    .split("\n")
    .map((line) => line.match(/^\|\s*(\d+\.\d+|te\.\d+)\s*\|([^|]*)\|/))
    .filter(Boolean)
    .map(([, legacyId, stableCell]) => ({ legacyId, stableId: stableCell.match(/ia\.[a-z0-9-]+/)?.[0] ?? null }));

const codeSpans = (markdown) => {
  const fenced = [...markdown.matchAll(/```[^\n]*\n([\s\S]*?)```/g)].flatMap(([, body]) => body.split("\n"));
  const withoutFences = markdown.replace(/```[\s\S]*?```/g, "");
  const inline = [...withoutFences.matchAll(/`([^`\n]+)`/g)].map(([, span]) => span);
  return [...fenced, ...inline];
};

const retiredMentions = (markdown, definition) => {
  const legacy = escapeRegExp(definition.legacy_id);
  const id = `(?<![\\w.])${legacy}(?![\\d])`;
  const patterns = [
    new RegExp(`^\\|\\s*${legacy}\\s*\\|`, "m"),
    new RegExp(`^#+\\s.*${id}`, "m"),
    new RegExp(`checkpoints?\\s+${id}`, "i"),
  ];
  const errors = [];
  if (patterns.some((pattern) => pattern.test(markdown))) errors.push(`lists retired checkpoint ${definition.legacy_id} (${definition.id})`);
  if (new RegExp(`${escapeRegExp(definition.id)}(?![a-z0-9-])`).test(markdown)) errors.push(`mentions retired stable id ${definition.id}`);
  return errors;
};

/** Lints one SKILL.md against the catalog. Returns a list of error messages. */
export const checkSkill = ({ skill, markdown, definitions, version }) => {
  const errors = [];
  const active = activeForSkill(skill, definitions);

  if (!markdown.includes(`Methodology version: \`${version}\``)) errors.push(`Methodology version: \`${version}\` is missing`);
  if (!markdown.includes(METHODOLOGY_URL)) errors.push(`the link to ${METHODOLOGY_URL} is missing`);

  const table = tableBlock(markdown);
  if (table === null) errors.push("the checkpoint table markers are missing");
  else if (table !== renderTable(active)) errors.push("the checkpoint table is out of date (run node scripts/sync-checkpoints.mjs)");

  const rows = tableRows(markdown);
  const listed = new Map(rows.map((row) => [row.legacyId, row.stableId]));
  for (const definition of active) {
    if (!listed.has(definition.legacy_id)) errors.push(`misses active checkpoint ${definition.legacy_id} (${definition.id})`);
    else if (listed.get(definition.legacy_id) !== definition.id) errors.push(`row ${definition.legacy_id} must use stable id ${definition.id}`);
    if (!markdown.includes(`<a id="${definition.id}"></a>`)) errors.push(`misses the anchor <a id="${definition.id}"></a>`);
  }
  const known = new Set(definitions.map((definition) => definition.legacy_id));
  for (const row of rows) {
    if (!known.has(row.legacyId)) errors.push(`lists unknown checkpoint ${row.legacyId}`);
  }

  for (const definition of definitions.filter(isRetired)) errors.push(...retiredMentions(markdown, definition));

  for (const span of codeSpans(markdown)) {
    if (/(^|[\s|;(])curl\s/.test(span) && !isReadOnlyCurl(span)) errors.push(`a curl command is not read-only: ${span.trim()}`);
  }
  return errors.map((error) => `${skill}/SKILL.md: ${error}`);
};

const parseArgs = (argv) => {
  const options = { check: false, snapshot: null, source: DEFAULT_SOURCE, root: null, skills: SKILLS };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    const value = () => {
      index += 1;
      if (argv[index] === undefined) throw new Error(`${arg} needs a value`);
      return argv[index];
    };
    if (arg === "--check") options.check = true;
    else if (arg === "--snapshot") options.snapshot = value();
    else if (arg === "--source") options.source = value();
    else if (arg === "--root") options.root = value();
    else if (arg === "--skills") options.skills = value().split(",").filter(Boolean);
    else throw new Error(`unknown argument ${arg}`);
  }
  return options;
};

const loadPayload = async (options, fetchImpl) => {
  if (options.snapshot) return JSON.parse(readFileSync(resolve(options.snapshot), "utf8"));
  const response = await fetchImpl(options.source, { headers: { accept: "application/json" } });
  if (!response.ok) throw new Error(`${options.source} returned HTTP ${response.status}`);
  return response.json();
};

const syncSkill = ({ skill, root, check, definitions, version }) => {
  const errors = [];
  const skillPath = join(root, skill, "SKILL.md");
  if (!existsSync(skillPath)) return [`${skill}/SKILL.md does not exist`];

  let markdown = readFileSync(skillPath, "utf8");
  const referencePath = join(root, skill, "references", "checkpoints.md");
  const reference = renderReference(skill, definitions, version);

  if (check) {
    const current = existsSync(referencePath) ? readFileSync(referencePath, "utf8") : null;
    if (current !== reference) errors.push(`${skill}/references/checkpoints.md is out of date (run node scripts/sync-checkpoints.mjs)`);
  } else {
    const updated = updateSkillTable(markdown, renderTable(activeForSkill(skill, definitions)));
    if (updated !== null && updated !== markdown) {
      writeFileSync(skillPath, updated);
      markdown = updated;
    }
    mkdirSync(dirname(referencePath), { recursive: true });
    writeFileSync(referencePath, reference);
  }
  return [...errors, ...checkSkill({ skill, markdown, definitions, version })];
};

/** Runs the command line interface. Returns the exit code. */
export const run = async (argv, io = {}) => {
  const log = io.log ?? console.log;
  const error = io.error ?? console.error;
  const fetchImpl = io.fetch ?? globalThis.fetch;

  let options;
  let catalog;
  try {
    options = parseArgs(argv);
    catalog = normalizePayload(await loadPayload(options, fetchImpl));
  } catch (cause) {
    error(`sync-checkpoints: ${cause.message}`);
    return EXIT.error;
  }

  const root = options.root ? resolve(options.root) : resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const validation = validateDefinitions(catalog.definitions);
  const errors = validation.length > 0
    ? validation
    : options.skills.flatMap((skill) => syncSkill({ skill, root, check: options.check, ...catalog }));

  if (errors.length > 0) {
    for (const line of errors) error(`  x ${line}`);
    error(`sync-checkpoints: ${errors.length} problem(s) found.`);
    return EXIT.fail;
  }
  log(`sync-checkpoints: ${options.check ? "checked" : "synced"} ${options.skills.join(", ")} against methodology ${catalog.version}.`);
  return EXIT.pass;
};

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  process.exitCode = await run(process.argv.slice(2));
}
